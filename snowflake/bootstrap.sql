USE ROLE SYSADMIN;
ALTER WAREHOUSE RMP_WH SET STATEMENT_TIMEOUT_IN_SECONDS=300 STATEMENT_QUEUED_TIMEOUT_IN_SECONDS=60;
-- Owner-approved fixture guard; a credit quota is not an exact dollar cap.
USE ROLE ACCOUNTADMIN;
CREATE RESOURCE MONITOR IF NOT EXISTS RMP_FIXTURE_BUDGET WITH CREDIT_QUOTA=1
  FREQUENCY=NEVER START_TIMESTAMP=IMMEDIATELY
  TRIGGERS ON 90 PERCENT DO SUSPEND ON 100 PERCENT DO SUSPEND_IMMEDIATE;
ALTER WAREHOUSE RMP_WH SET RESOURCE_MONITOR=RMP_FIXTURE_BUDGET;
